"""Pack the dashboard's data files into data.js.

The page loads data.js with a plain <script> tag, so it works both on GitHub
Pages and when index.html is opened straight from disk (browsers block
fetch() of local files).

Refresh the figures:
    1. python transport_dashboard.py --export-snapshot OUT D:\\Ireland\\CSO_PxStat
       (or replace any CSV in data/ with a new export, same columns)
    2. python build_data.py
    3. commit and push; GitHub Pages republishes in a minute or two.
"""
import datetime
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
DATA = HERE / "data"


def main() -> None:
    csv = {p.stem: p.read_text(encoding="utf-8") for p in sorted(DATA.glob("*.csv"))}
    geo = json.loads((DATA / "ireland_counties.geojson").read_text(encoding="utf-8"))
    # other JSON data files (e.g. galway_flows.json from make_galway_flows.py), by file name
    extra = {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in sorted(DATA.glob("*.json"))}
    built = datetime.date.today().isoformat()
    out = (
        "// Generated by build_data.py - do not edit by hand.\n"
        f"window.TX_BUILT = {json.dumps(built)};\n"
        f"window.TX_CSV = {json.dumps(csv, ensure_ascii=False)};\n"
        f"window.TX_JSON = {json.dumps({'ireland_map': geo, **extra}, separators=(',', ':'), ensure_ascii=False)};\n"
    )
    (HERE / "data.js").write_text(out, encoding="utf-8")
    # stamp a new version on every script so browsers fetch fresh copies
    stamp = datetime.datetime.now().strftime("%Y%m%d%H%M")
    page = HERE / "index.html"
    html = re.sub(r'(<script src="[\w.-]+\.js)(\?v=\d+)?"', rf'\1?v={stamp}"', page.read_text(encoding="utf-8"))
    page.write_text(html, encoding="utf-8")
    print(f"data.js: {len(csv)} tables + map + {len(extra)} JSON, {len(out) / 1024:.0f} KB, built {built}")


if __name__ == "__main__":
    main()
